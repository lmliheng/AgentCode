
/**
 * @propmts对象
 * 
 * 
 */
export default class Prompts {

    text: string
    constructor(text?: string) {
        this.text = text ?? ''
    }
    /**
     * 输出json格式的回答，这里只是在提示词这块进行响应约束
     */
    json() {
        return `请将以下关于${this.text}的信息整理成严格的JSON格式输出。输出必须是一个有效的JSON对象，不要包含任何markdown代码块标记（如\`\`\`json）或其他解释性文字。

字段定义：
- "name": [字符串，代表名称]
- "features": [字符串数组，列出主要特点，至少3个]
- "rating": [数字，1到10之间的整数，代表综合评分]

主题：${this.text}

请确保JSON格式正确，键名使用双引号。`
    }

    /**
     * @响应格式是markdown的表格
     */
    table() {
        return `请将以下关于${this.text}的信息整理成Markdown表格格式输出。

要求：
- 使用Markdown表格语法（| 列1 | 列2 | ...）
- 表格应包含合适的列名（如：名称、特点、评分等）
- 内容应围绕主题"${this.text}"展开
- 特点列可以用换行（<br>）或列表形式展示多个特点
- 不要包含多余的说明文字，直接输出表格

示例格式：
| 名称 | 主要特点 | 综合评分 |
|------|----------|----------|
| ...  | ...      | ...      |`
    }

    /**
     * @评分
     */
    rate() {
        return `请对"${this.text}"进行综合评价并给出评分。

要求：
- 评分范围为1到10分（整数）
- 请给出评分理由，从多个维度进行分析（如：实用性、创新性、性价比、易用性等）
- 输出格式：
  - 总分：[数字]/10
  - 各维度评分及简要说明
  - 总结性评价（2-3句话）

请客观、公正地进行评价。`
    }

    /**
     * @拒绝回答
     * 用在系统提示词里
     */
    refuse(refuse_text: string) {
        return `当用户提问涉及${refuse_text}相关的内容时，请礼貌地拒绝回答。

拒绝话术要求：
- 语气友好、礼貌，不要生硬
- 简要说明无法回答的原因（如：涉及敏感信息、超出知识范围、违反安全策略等）
- 可以提供替代建议（如：建议用户咨询相关专业人士、查阅官方资料等）
- 不要透露任何关于${refuse_text}的具体信息

示例回复风格：
"抱歉，关于这个话题我暂时无法为您提供详细信息。建议您[替代建议]。如有其他问题，欢迎继续提问。"`
    }

    /**
     * @给回答加上引用
     */
    quote() {
        return `请围绕"${this.text}"提供详细的信息，并在回答中附上引用来源。

引用要求：
- 每个关键论点或数据都必须标注引用来源
- 引用格式：[来源名称](URL) 或 [来源名称]（如果无URL）
- 在回答末尾统一列出"参考资料"列表
- 确保引用来源可靠、可查证
- 如果信息不确定，请明确标注"待验证"

回答结构：
1. 正文内容（含内联引用）
2. 参考资料列表（编号对应正文中的引用）

请确保信息准确，引用规范。`
    }
}